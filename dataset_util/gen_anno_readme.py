#!/usr/bin/env python3
"""Regenerate anno_online/README.md from what is actually on disk."""
import json, os, sys

ROOT = "anno_online"
def mb(p): return os.path.getsize(p) / 1048576

INTERNVID_DESC = {
 "pool_all_qwen3vl.json":        ("master", "Every InternVid clip with its Qwen3-VL-8B re-caption. Source of every file below; nothing else can be rebuilt without it."),
 "phase1_lt180.json":            ("Phase 1", "`< 180 s` bucket — the qbase pretrain set."),
 "phase2_mid_180_420.json":      ("Phase 2", "`180–420 s` bucket — the fold's main signal."),
 "phase2_lt180_replay.json":     ("Phase 2", "`< 180 s` replay — shallow-fold signal + short-video retention."),
 "phase2_qbase_replay.json":     ("Phase 2", "`< 180 s` pure-qbase replay (`qbase_only: true`) — keeps the projector on the raw-qbase manifold."),
 "phase3_src_mid_420_1200.json": ("Phase 3 src", "`420–1200 s` bucket, FULL. Input to build_phase3_blend.py --merge; the subsampled copy that actually trains is phase3/train/internvid_mid_420_1200.json."),
 "phase3_src_lt420_replay.json": ("Phase 3 src", "`< 420 s` fold replay, FULL. Same: subsampled into phase3/train/."),
 "phase3_src_qbase_replay.json": ("Phase 3 src", "`< 420 s` pure-qbase replay, FULL. Same."),
}

out = []
w = out.append
w("# `anno_online/` — annotation files\n")
w("Generated by `dataset_util/gen_anno_readme.py`; re-run it after rebuilding any registry.\n")
w("**These are the annotation payloads. The registries that point at them live in `anno_data/`**")
w("(a `--multi_dataset` meta JSON: `{task: {annotation, data_root, online_mode, prefix_captioning}}`).")
w("Training never reads this directory directly — it reads one `anno_data/*.json` registry,")
w("which names the files here by absolute path.\n")
w("```")
w("anno_online/")
w("├── internvid/     8 files  — the InternVid pool + the length buckets sliced from it")
w("└── phase3/")
w("    ├── train/    one file per registered task  (anno_data/phase3_blend.json)")
w("    └── heldout/  its per-task held-out slice   (anno_data/phase3_heldout.json)")
w("```\n")
w("One file per task is not redundancy: the `--multi_dataset` format takes exactly one")
w("annotation path per registry entry, and the per-task held-out policy (docs §6) needs each")
w("task's eval slice to be separately addressable.\n")

w("## `internvid/` — InternVid, Qwen3-VL re-captions\n")
w("All eight are slices of `pool_all_qwen3vl.json`, kept materialised because slicing 977k rows")
w("is slower than reading a file. `data_root` for all of them is `/share/dataset/internVid`.\n")
w("| file | used by | size | rows | what it is |")
w("|---|---|---:|---:|---|")
d = os.path.join(ROOT, "internvid")
for fn in sorted(os.listdir(d), key=lambda f: (INTERNVID_DESC.get(f, ("z",))[0] != "master", f)):
    p = os.path.join(d, fn)
    phase, desc = INTERNVID_DESC.get(fn, ("?", "unrecognised — not produced by any current builder"))
    n = len(json.load(open(p)))
    w(f"| `{fn}` | {phase} | {mb(p):,.0f} MB | {n:,} | {desc} |")
w("")
w("Rebuild:")
w("```bash")
w("# master (from the re-caption jsonl)")
w("python dataset_util/captions_jsonl_to_stage1_anno.py --captions recaption/qwen3vl/captions.jsonl \\")
w("  --anno_out anno_online/internvid/pool_all_qwen3vl.json \\")
w("  --meta_out anno_data/internvid_qwen3vl.json --data_root /share/dataset/internVid")
w("# Phase 1 bucket")
w("python dataset_util/build_internvid_phase1_anno.py           # defaults write phase1_lt180.json")
w("# Phase 2 buckets  ->  anno_data/phase2_internvid.json")
w("python dataset_util/build_phase2_manifest.py --prefix phase2 --mid_lo 180 --mid_hi 420 \\")
w("  --meta_out anno_data/phase2_internvid.json")
w("# Phase 3 source buckets  ->  anno_data/phase3_internvid.json")
w("python dataset_util/build_phase2_manifest.py --prefix phase3_src --mid_lo 420 --mid_hi 1200 \\")
w("  --meta_out anno_data/phase3_internvid.json")
w("```\n")

for split, reg in (("train", "anno_data/phase3_blend.json"),
                   ("heldout", "anno_data/phase3_heldout.json")):
    if not os.path.exists(reg):
        continue
    m = json.load(open(reg))
    d = os.path.join(ROOT, "phase3", split)
    files = sorted(os.listdir(d)) if os.path.isdir(d) else []
    tot_rows = 0
    rows_tbl = []
    for name, cfg in m.items():
        p = cfg["annotation"]
        n = len(json.load(open(p)))
        tot_rows += n
        rows_tbl.append((name, os.path.basename(p), n, mb(p), cfg["data_root"]))
    w(f"## `phase3/{split}/` — {len(files)} files, {tot_rows:,} rows\n")
    w(f"Registry: `{reg}`. " + (
        "This is what `--data_path` points at for a Phase-3 run."
        if split == "train" else
        "The held-out counterpart, disjoint from train by video. "
        "`eval_ablation/manifest_phase3_heldout.json` lists the same clips as a video manifest."))
    w("")
    w("| task | rows | size | data_root |")
    w("|---|---:|---:|---|")
    for name, fn, n, size, root in sorted(rows_tbl, key=lambda r: -r[2]):
        w(f"| `{name}` | {n:,} | {size:,.1f} MB | `{root}` |")
    w("")
    orphan = [f for f in files if os.path.join(os.path.abspath(d), f)
              not in {os.path.abspath(c["annotation"]) for c in m.values()}]
    if orphan:
        w(f"**Orphans (on disk, not in the registry — safe to delete):** {orphan}\n")

w("Rebuild both at once (deterministic given `--seed`):")
w("```bash")
w("python dataset_util/build_phase3_blend.py \\")
w("  --datasets_root /root/datasets \\")
w("  --merge anno_data/phase3_internvid.json --merge_share 0.35 \\")
w("  --protect_from anno_data/phase2_internvid.json anno_data/internvid_qwen3vl_lt180.json \\")
w("  --probe_durations --force")
w("```")
w("`--merge_share` is the InternVid fraction (it is the only source of 420–1200 s clips, so it")
w("cannot go to 0 — raise it for deeper folds, lower it for denser annotation).")
w("Drop `--probe_durations` to reuse `anno_data/phase3_durations.json` unchanged.\n")

open(os.path.join(ROOT, "README.md"), "w").write("\n".join(out) + "\n")
print(f"wrote {ROOT}/README.md ({len(out)} lines)")

# ----------------------------------------------------------------- anno_data
DATA_DESC = {
 "internvid_qwen3vl.json":       "Registry: the whole InternVid re-caption pool (1 entry). Phase-1 experiments that want everything.",
 "internvid_qwen3vl_lt180.json": "Registry: Phase 1 training set (`< 180 s`). Also passed to build_phase3_blend.py --protect_from.",
 "phase2_internvid.json":        "Registry: Phase 2 training set (3 streams). Also --protect_from for the Phase-3 split.",
 "phase3_internvid.json":        "Registry: the FULL InternVid Phase-3 source buckets. Not trained on directly -- it is the --merge input to build_phase3_blend.py, which subsamples it to --merge_share.",
 "phase3_blend.json":            "Registry: **the Phase-3 training set** (31 tasks). This is --data_path for shell/pretrain_phase3_budget.sh.",
 "phase3_heldout.json":          "Registry: the per-task held-out slices (29 tasks), disjoint from phase3_blend by video.",
 "internVid_durations.json":     "ffprobe scan of the InternVid pool. Seed for phase3_durations.json; --durations for build_phase2_manifest.py.",
 "internVid_durations_stats.json": "Summary of the above (percentiles, bucket histogram). Reference only, nothing reads it.",
 "phase3_durations.json":        "`{stem: duration}` covering every clip in phase3_blend + phase3_heldout. DURATIONS_JSON for the Phase-3 launcher; without it --group_by_compression_depth silently collapses to one depth class.",
}
out2 = []
v = out2.append
v("# `anno_data/` — dataset registries + duration scans\n")
v("Generated by `dataset_util/gen_anno_readme.py`.\n")
v("A **registry** is the `--multi_dataset` meta JSON a training run is pointed at with")
v("`--data_path`: `{task: {annotation, data_root, online_mode, prefix_captioning}}`. The")
v("annotation payloads it names live in `anno_online/` (see its README). There is no per-entry")
v("weight in this format, so **the mix ratio is the row counts of the annotation files**.\n")
v("| file | kind | entries / clips | what it is |")
v("|---|---|---:|---|")
for fn in sorted(os.listdir("anno_data")):
    if not fn.endswith(".json"):
        continue
    fp = os.path.join("anno_data", fn)
    d = json.load(open(fp))
    if isinstance(d, dict) and d and all(isinstance(x, dict) and "annotation" in x for x in d.values()):
        kind, n = "registry", f"{len(d)} tasks"
        dead = [k for k, c in d.items() if not os.path.exists(c["annotation"])]
        if dead:
            kind = "registry **BROKEN**"
            n += f" ({len(dead)} dead)"
    elif fn.endswith("_stats.json"):
        kind, n = "summary", "--"
    else:
        kind, n = "durations", f"{len(d):,} clips"
    v(f"| `{fn}` | {kind} | {n} | {DATA_DESC.get(fn, 'unrecognised')} |")
v("")
open("anno_data/README.md", "w").write("\n".join(out2) + "\n")
print(f"wrote anno_data/README.md ({len(out2)} lines)")
